# 6) Print each element using for loop
nums = [10, 20, 30, 40, 50]

print("Elements in the list:")
for x in nums:
    print(x)

print("------------------------")

# 7) Sum of all elements
total = sum(nums)
print("Sum of all elements:", total)

print("------------------------")

# 8) Largest and Smallest number
largest = max(nums)
smallest = min(nums)

print("Largest number:", largest)
print("Smallest number:", smallest)
